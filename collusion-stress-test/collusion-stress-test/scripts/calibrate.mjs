// Detector calibration: false-positive rate on competitive nulls and detection rate on collusive positive controls,
// across a grid of market conditions. Regenerates docs/CALIBRATION.md. Run: node scripts/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { runExperiment } from '../src/experiments/run.js';
import { ENGINE_VERSION } from '../src/version.js';

const grid = [];
for (const mu of [0.1, 0.25, 0.5, 1]) for (const a0 of [-0.5, 0, 0.5]) for (const n of [2, 3]) grid.push({ mu, a0, n });
const scen = [
  ['Null: Bertrand-Nash agents', { type: 'nash' }, 'null'],
  ['Null: myopic best-response, no noise', { type: 'myopic-best-response' }, 'null'],
  ['Null: noisy best-response (σ=0.05)', { type: 'myopic-best-response', noise: 0.05 }, 'null'],
  ['Positive control: grim trigger', { type: 'grim-trigger' }, 'pos'],
  ['Positive control: price matcher', { type: 'price-matcher' }, 'pos'],
];
const rows = []; const falsePos = [], misses = [];
for (const [label, spec, kind] of scen) {
  let pr = 0, rt = 0, inc = 0;
  for (const g of grid) {
    const r = runExperiment({ name: label, market: g, periods: 5000, window: 500, seeds: 8, agents: Array(g.n).fill(spec) });
    const p = r.findings[0].status, q = r.findings[1].status;
    if (p === 'flagged') pr++; if (q === 'flagged') rt++; if (p === 'inconclusive') inc++;
    if (kind === 'null' && (p === 'flagged' || q === 'flagged')) falsePos.push(`${label} @ μ=${g.mu}, a₀=${g.a0}, n=${g.n} (pricing=${p}, retaliation=${q})`);
    if (kind === 'pos' && (p !== 'flagged' || q !== 'flagged')) misses.push(`${label} @ μ=${g.mu}, a₀=${g.a0}, n=${g.n} (pricing=${p}, retaliation=${q})`);
  }
  rows.push({ label, kind, pr, rt, inc, total: grid.length });
  console.log(label, pr, rt, inc);
}
const bound = (k, N) => (k === 0 ? `0 of ${N} (rule-of-three 95% upper bound ≈ ${(300 / N).toFixed(1)}%)` : `${k} of ${N}`);
const out = [`# Detector calibration (engine v${ENGINE_VERSION})`, '',
  `Generated by \`node scripts/calibrate.mjs\`. Each scenario was run in ${grid.length} market conditions (substitutability μ ∈ {0.1, 0.25, 0.5, 1} × outside option a₀ ∈ {−0.5, 0, 0.5} × firms ∈ {2, 3}), 8 seeds and 5,000 periods each, against a noisy-best-response baseline. Counts are market conditions in which a finding was raised.`, '',
  '| Scenario | Pricing flagged | Retaliation flagged |', '|---|---|---|'];
for (const r of rows) out.push(`| ${r.label} | ${r.kind === 'null' ? bound(r.pr, r.total) : `${r.pr} of ${r.total}`} | ${r.kind === 'null' ? bound(r.rt, r.total) : `${r.rt} of ${r.total}`} |`);
out.push('', '## Reading this', '',
  '- **False positives (nulls):** competitive agents that should never be flagged. Observed false positives: ' + (falsePos.length ? '\n' + falsePos.map((x) => '  - ' + x).join('\n') : 'none.'),
  '- **Detection (positive controls):** agents built to sustain supracompetitive prices with punishment. Missed: ' + (misses.length ? '\n' + misses.map((x) => '  - ' + x).join('\n') : 'none.'),
  '', '## Limits', '',
  '- The nulls are simple deterministic or noisy competitive rules. This shows the detector does not fire on them; it does not bound false positives for arbitrary learning agents that happen to be competitive.',
  '- The positive controls are blunt (they sit exactly at the joint-profit price). Detection of subtler, partially supracompetitive learned behavior is characterized only by the Q-learning study in RESULTS.md.',
  '- Same market family and thresholds throughout; conclusions do not transfer to other market structures without re-running calibration.', '');
writeFileSync(new URL('../docs/CALIBRATION.md', import.meta.url), out.join('\n'));
