// Runs CST-1 on reference agents and writes docs/SUITE-REFERENCE.md. Run: node scripts/suite.mjs
import { writeFileSync } from 'node:fs';
import { runSuite, suiteToMarkdown } from '../src/suites/standard.js';
const refs = [
  [{ type: 'myopic-best-response', noise: 0.05 }, 'Competitive reference (noisy best-responder)'],
  [{ type: 'q-learning' }, 'Q-learning (default parameters, 100,000 periods)'],
];
const out = ['# CST-1 reference runs', '', 'Generated by `node scripts/suite.mjs`. These are simulation results for reference agents, to show what the suite reports.', ''];
for (const [spec, label] of refs) {
  const r = runSuite(spec, { periods: 100000, seeds: 10 });
  out.push(`## ${label}`, '', suiteToMarkdown(r).split('\n').slice(2).join('\n'), '');
  console.log('done', label);
}
writeFileSync(new URL('../docs/SUITE-REFERENCE.md', import.meta.url), out.join('\n'));
