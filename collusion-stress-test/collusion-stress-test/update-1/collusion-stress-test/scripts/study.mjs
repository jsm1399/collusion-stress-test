// Reproducible study: regenerates docs/RESULTS.md. Run: node scripts/study.mjs
import { writeFileSync } from 'node:fs';
import { runExperiment } from '../src/experiments/run.js';
import { runSweep } from '../src/experiments/sweep.js';
import { ENGINE_VERSION } from '../src/version.js';

const f = (x) => Number(x).toFixed(3), ci = (s) => `${f(s.mean)} [${f(s.ci[0])}, ${f(s.ci[1])}]`;
const Q2 = { name: 'Two Q-learning agents', market: { n: 2 }, periods: 200000, seeds: 10, agents: [{ type: 'q-learning' }, { type: 'q-learning' }] };
const out = [`# Simulation results (engine v${ENGINE_VERSION})`, '',
  'Generated by `node scripts/study.mjs`. **These are results demonstrated by our simulations** in one stylized market (symmetric logit-demand Bertrand, Calvano et al. 2020 design); they are not evidence about any real firm and not legal conclusions. Δ = 0 is the competitive (Nash) benchmark, Δ = 1 the joint-profit maximum. Tables show mean [95% bootstrap CI over seeds]. Baseline = noisy myopic best-responders.', ''];

const main = runExperiment({ ...Q2, seeds: 20 });
const S = main.groups.test.summary;
out.push('## 1. Two independent Q-learning agents (20 seeds, 200,000 periods, α=0.15, β=10/periods)', '',
  `- Δ: ${ci(S.delta)}; competitive baseline Δ: ${ci(main.groups.baseline.summary.delta)}`,
  `- Price premium over Nash: ${ci(S.premium)}`,
  `- Rivals' price cut after forced deviation, share of premium: ${ci(S.rivalCutShare)}; discounted gain from deviating: ${ci(S.discountedGain)}`,
  `- Findings: pricing = ${main.findings[0].status}, retaliation = ${main.findings[1].status}`,
  `- Seeds with Δ ≥ 0.1: ${main.groups.test.perSeed.filter((r) => r.delta >= 0.1).length} of ${main.config.seeds}; range of Δ: ${f(Math.min(...main.groups.test.perSeed.map((r) => r.delta)))} to ${f(Math.max(...main.groups.test.perSeed.map((r) => r.delta)))}`, '');

let k = 2;
for (const sw of [{ path: 'market.mu', values: [0.1, 0.25, 0.5, 1] }, { path: 'market.n', values: [2, 3] }, { path: 'agent.beta', values: [0.00002, 0.00005, 0.0001] }]) {
  const s = runSweep(Q2, sw);
  out.push(`## ${k++}. Sweep: ${s.label} (10 seeds each)`, '', `| ${s.label} | Δ test | Δ baseline | Price premium | Rival cut share | Pricing | Retaliation |`, '|---|---|---|---|---|---|---|');
  for (const p of s.points) out.push(`| ${p.value} | ${ci(p.delta)} | ${f(p.baselineDelta.mean)} | ${f(p.premium.mean)} | ${f(p.rivalCutShare.mean)} | ${p.pricing} | ${p.retaliation} |`);
  out.push('');
  console.log('done', sw.path);
}
out.push('## Limits', '', '- Single market family; symmetric firms; fixed run length (200k periods is far shorter than the multi-million-period runs in the literature, so results may understate or differ from converged behavior).', '- With 3 firms the state space is 15³ = 3,375 states; 200k periods gives each state far fewer visits, so n=3 results reflect less-trained agents.', '- Findings thresholds are screening parameters, not calibrated error rates.', '');
writeFileSync(new URL('../docs/RESULTS.md', import.meta.url), out.join('\n'));
console.log('written');
